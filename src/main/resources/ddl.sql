-- PostgreSQL 스키마. 컬럼명은 Spring 기본 네이밍(camelCase -> snake_case)과 엔티티 @Table 이름을 따른다.
-- LocalDateTime은 Hibernate PostgreSQLDialect 기본값인 timestamp(6)에 맞춘다.
-- PK 인덱스는 id 조회(findById, existsById)에 쓰인다.

CREATE TABLE IF NOT EXISTS users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(50)  NOT NULL,
    password   VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6)    NOT NULL,
    updated_at TIMESTAMP(6)    NOT NULL,
    deleted_at TIMESTAMP(6),
    -- existsByUsername, findByUsername
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS follow_counts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT    NOT NULL,
    followers_count  BIGINT    NOT NULL,
    followees_count  BIGINT    NOT NULL,
    created_at       TIMESTAMP(6) NOT NULL,
    updated_at       TIMESTAMP(6) NOT NULL,
    deleted_at       TIMESTAMP(6),
    -- findByUserId, increment/decrement*Count 의 WHERE user_id = ?
    -- count > 0 조건은 유니크 조회 이후 한 행에만 적용되므로 별도 인덱스는 두지 않는다.
    CONSTRAINT uk_follow_counts_user_id UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS follows (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT    NOT NULL,
    followee_id BIGINT    NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,
    deleted_at  TIMESTAMP(6)
);

-- 소프트 삭제(deleted_at)된 행은 재팔로우를 막지 않도록 삭제되지 않은 행에만 유니크를 건다.
-- existsByFollowerIdAndFolloweeId, 언팔로우 UPDATE ... WHERE follower_id = ? AND followee_id = ?
-- 기존 DB에 남아 있는 전체 유니크 제약은 제거한다(신규 DB에서는 no-op).
ALTER TABLE follows DROP CONSTRAINT IF EXISTS uk_follows_follower_followee;

CREATE UNIQUE INDEX IF NOT EXISTS uk_follows_follower_followee
    ON follows (follower_id, followee_id) WHERE deleted_at IS NULL;

-- findAllByFollowerIdOrderByCreatedAtDesc
-- 유니크 키 (follower_id, followee_id)는 followee_id가 created_at보다 앞에 있어 정렬에 쓸 수 없다.
CREATE INDEX IF NOT EXISTS idx_follows_follower_id_created_at ON follows (follower_id, created_at DESC);

-- findAllByFolloweeIdOrderByCreatedAtDesc
-- 유니크 키는 follower_id로 시작하므로 followee_id 등호 조건을 타지 못한다.
CREATE INDEX IF NOT EXISTS idx_follows_followee_id_created_at ON follows (followee_id, created_at DESC);

-- 게시글/답글(parent_id)/인용글(quote_id)/리포스트(repost_id)를 한 테이블로 표현한다.
-- 리포스트만 content가 null이고, 나머지는 작성 시점에 서비스에서 필수로 검증한다.
CREATE TABLE IF NOT EXISTS posts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    content      VARCHAR(500),
    parent_id    BIGINT,
    quote_id     BIGINT,
    repost_id    BIGINT,
    reply_count  INTEGER      NOT NULL DEFAULT 0,
    repost_count INTEGER      NOT NULL DEFAULT 0,
    like_count   INTEGER      NOT NULL DEFAULT 0,
    view_count   BIGINT       NOT NULL DEFAULT 0,
    created_at   TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    deleted_at   TIMESTAMP(6)
);

-- existsByUserIdAndRepostId / findByUserIdAndRepostId
-- 소프트 삭제된 리포스트는 재리포스트를 막지 않도록 삭제되지 않은 행에만 유니크를 건다.
CREATE UNIQUE INDEX IF NOT EXISTS uk_posts_user_id_repost_id
    ON posts (user_id, repost_id) WHERE repost_id IS NOT NULL AND deleted_at IS NULL;

-- findAllByParentIdOrderByCreatedAtAsc
CREATE INDEX IF NOT EXISTS idx_posts_parent_id_created_at ON posts (parent_id, created_at);

-- findAllByQuoteIdOrderByCreatedAtDesc
CREATE INDEX IF NOT EXISTS idx_posts_quote_id_created_at ON posts (quote_id, created_at DESC);

-- findAllByRepostIdOrderByCreatedAtDesc
CREATE INDEX IF NOT EXISTS idx_posts_repost_id_created_at ON posts (repost_id, created_at DESC);

-- 사용자별 타임라인 확장용. 단건 조회는 PK를 쓴다.
CREATE INDEX IF NOT EXISTS idx_posts_user_id_created_at ON posts (user_id, created_at DESC);
